def source_rows_local(path):
    with path.open() as f:return list(prior.csv.DictReader(f))
def check_links(paths):
    count=0
    for path in paths:
        text=path.read_text()
        targets=re.findall(r'\]\(([^\s)]+)(?:\s+"[^"]*")?\)',text)
        definitions=dict(re.findall(r'^\[([^\]]+)\]:\s*(\S+)',text,re.M))
        for label in re.findall(r'\]\[([^\]]+)\]',text):assert label in definitions,'MISSING_REFERENCE '+label
        targets+=list(definitions.values())
        for target in targets:
            parsed=urlparse(target)
            if parsed.scheme:
                m=re.match(r'https://github.com/HIROMU1015/Partially-Randomized-Trotter/(?:blob|tree)/([0-9a-f]{40})/(.*)',target)
                if m:subprocess.run(['git','cat-file','-e',m[1]+':'+unquote(m[2]).split('#')[0]],cwd=ROOT,check=True,stdout=subprocess.DEVNULL);count+=1
                continue
            if target.startswith('#'):continue
            p=(path.parent/unquote(target.split('#')[0])).resolve();assert p.exists(),str(path)+' -> '+target;count+=1
    return count
