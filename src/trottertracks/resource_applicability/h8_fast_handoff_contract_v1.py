def verify_template(root, m, *, worker=False):
    root = Path(root)
    parent = private_path(m['old_parent']['directory'])
    require_retired_continuation(parent)
    if (m['scope'] != 'REMAINING_FAST' or m['H8_full_campaign_authorized'] is not False
        or m['retry'] is not False or m['seed_source_commit'] != OLD_SOURCE
        or m['validation_method'] != METHOD or m['validation_method_changed'] is not True):
        raise ValueError('HANDOFF_FIXED_FLAGS')
    for name, h in m['old_parent']['pending_hashes'].items():
        if file_hash(parent/name) != h:
            raise ValueError('PENDING_PARENT_CHANGED:'+name)
    if set(m['old_parent']['pending_hashes']) != set(PENDING_NAMES):
        raise ValueError('PENDING_PARENT_CLOSURE')
    # Regenerate metadata only, keeping the existing output allowed after claim.
    signal_m = read(parent/'signal01/manifest.json'); heavy_m = read(parent/'heavy01/manifest.json')
    signals = read(Path(m['signal_binding']['path']))
    if file_hash(m['signal_binding']['path']) != m['signal_binding']['sha256']:
        raise ValueError('SIGNAL_SUMMARY_CHANGED')
    if digest(m['registrations']) != digest(remaining_registrations(signals)):
        raise ValueError('ORIGINAL_SEED_OR_TASK_CHANGED')
    if digest(m['plan']) != digest(plan()) or m['profile'] != profile():
        raise ValueError('HANDOFF_PLAN_PROFILE')
    if (m['input_identity'] != input_identity(m['input_identity']['directory'])
        or m['input_identity'] != heavy_m['input_identity'] or m['cumulative_carry'] != heavy_m['cumulative_carry']):
        raise ValueError('HANDOFF_INPUT_OR_CARRY')
    if (m['proposed_resources'] != resources('REMAINING',3) or m['observation_policy'] != observation('REMAINING',3)
        or m['base_manifest'] != heavy_m['base_manifest'] or m['compiler_hash'] != COMPILER):
        raise ValueError('HANDOFF_RESOURCE_COMPILER')
    budget = dict(parent_complete_compile=2, remaining_compile=18, total_compile=20,
        parent_trajectory=0, remaining_trajectory=4, total_trajectory=4, remaining_occurrence=15,
        parent_control_probe=4, remaining_control_probe=36, total_control_probe=40,
        new_signal_calls=0, old_pending_pipeline_calls=0, refund=0, reset=False)
    if m['handoff_budget'] != budget:
        raise ValueError('HANDOFF_BUDGET_CHANGED')
    private_path(m['output'])
    if set(m['source_hashes']) != set(source_paths(root)):
        raise ValueError('HANDOFF_SOURCE_CLOSURE')
    if not worker:
        subprocess.run(['git','merge-base','--is-ancestor',FAST_SOURCE,m['source_commit']],cwd=root,check=True,
                       stdout=subprocess.DEVNULL)
        subprocess.run(['git','merge-base','--is-ancestor',m['source_commit'],'HEAD'],cwd=root,check=True,
                       stdout=subprocess.DEVNULL)
    for p, h in m['source_hashes'].items():
        if file_hash(root/p) != h:
            raise ValueError('HANDOFF_SOURCE_CHANGED:'+p)
        if not worker:
            import hashlib
            if hashlib.sha256(subprocess.check_output(['git','show',m['source_commit']+':'+p],cwd=root)).hexdigest() != h:
                raise ValueError('HANDOFF_SOURCE_BLOB:'+p)
    if any(m['source_hashes'].get(p) != h for p, h in heavy_m['source_hashes'].items()):
        raise ValueError('HANDOFF_OLD_SCIENCE_CHANGED')
    return True


def admit_heavy(parent, *, check_processes=True):
    parent = private_path(parent); d = parent/'heavy01'; w = d/'cost_exploration_0003'
    if not (d/'execution_terminal.json').exists():
        return None
    t = read(d/'execution_terminal.json'); wt = read(w/'worker_terminal.json')
    m = read(d/'manifest.json'); task = m['registrations'][0]['task']
    if (m['source_commit'] != OLD_SOURCE or m['scope'] != 'HEAVY'
        or [r['index'] for r in m['registrations']] != [3]
        or t['first_stop_reason'] is not None or t['completed_indices'] != [3]
        or not t['all_dispatched_reaped'] or t['cleanup_errors']
        or len(t['retired']) != 1 or t['retired'][0]['exit_code'] != 0
        or wt['status'] != 'COMPLETE' or wt['reason'] is not None
        or wt['source_commit'] != OLD_SOURCE or wt['scope'] != 'HEAVY'):
        raise ValueError('OLD_HEAVY_STOP_OR_INCOMPLETE')
    r = read(w/'cost_result.json'); trajectory = read(w/'trajectory.json')
    if r['task'] != task or trajectory['task'] != task or trajectory['events'] is not None or trajectory['event_digest'] != digest(None):
        raise ValueError('OLD_HEAVY_TASK_OR_EVENTS')
    if { (x['axis'],x['control']) for x in r['rows']} != {('cosine','symmetric_directional'),('sine','symmetric_directional')} or len(r['rows']) != 2:
        raise ValueError('OLD_HEAVY_PAIRED_WRAPPERS')
    for row in r['rows']:
        if (any(row[k] != task[k] for k in ('cell_id','phase','replica','seed'))
            or row['compiler_hash'] != COMPILER or len(row['fingerprint']) != 64
            or row['event_digest'] != trajectory['event_digest']
            or set(row['metrics']) != {'RZ','CX','RZ_depth','CX_depth','depth','size'}
            or any(type(v) is not int or v < 0 for v in row['metrics'].values())
            or read(w/f"wrapper_{row['control']}_{row['axis']}.json") != row):
            raise ValueError('OLD_HEAVY_WRAPPER_CHANGED')
    calls = r['calls_attempted']
    if any(calls[k] != v for k,v in dict(compile=2,trajectory=0,occurrence=0,control_probe=4,primitive=0,reference_matvec=0).items()):
        raise ValueError('OLD_HEAVY_CALLS')
    error = read(w/'validation_symmetric_directional.json')['max_error']
    if not isinstance(error,(int,float)) or not 0 <= error <= 1e-9:
        raise ValueError('OLD_HEAVY_CONTROL')
    coordinator = read(parent/'launch-heavy01.json')['identity']
    claim = read(w/'worker_claim.json')
    if check_processes and (not inactive(coordinator) or not inactive(claim['identity'])):
        return None
    return dict(status='ACCEPTED_COMPLETE_HEAVY', source_commit=OLD_SOURCE,
        parent_directory=str(d), file_hashes={n:file_hash(d/n) for n in HEAVY_FINAL_NAMES},
        calls_attempted=calls, worker_exit_code=0,
        coordinator_exit_code=None, exact_exit_timestamp=None,
        native_coordinator_wait_status_recorded=False, all_workers_reaped=True,
        old_coordinator_inactive=True, cleanup_errors=[], result=r,
        original_coordinator_identity=coordinator, original_worker_identity=claim['identity'])


def verify_authorization(m, g):
    if (g.get('schema') != 'h8_fast_handoff_authorization_v1' or g.get('approved_by_user') is not True
        or g.get('authorization_basis') != AUTHORIZATION or g.get('one_shot') is not True
        or g.get('retry') is not False or g.get('H8_full_campaign_authorized') is not False
        or g.get('manifest_sha256') != digest(m) or g.get('source_commit') != m['source_commit']
        or g.get('output') != m['output']):
        raise ValueError('HANDOFF_NEW_AUTH_BINDING')


def finalized(template, heavy):
    if heavy is None or heavy['status'] != 'ACCEPTED_COMPLETE_HEAVY':
        raise ValueError('HEAVY_COMPLETION_REQUIRED')
    m = deepcopy(template); m['schema'] = 'h8_bound_remaining_fast_handoff_v1'
    m['accepted_heavy'] = heavy; m['technical_plan_sealed'] = True
    g = dict(schema='h8_fast_handoff_authorization_v1', approved_by_user=True,
        authorization_basis=AUTHORIZATION, manifest_sha256=digest(m), source_commit=m['source_commit'],
        output=m['output'], one_shot=True, retry=False, H8_full_campaign_authorized=False,
        automatic_next_full_campaign=False, mandatory_stop=True)
    return m, g


def verify_binding(root, m, g, *, worker=False):
    verify_template(root, m, worker=worker); verify_authorization(m,g)
    if m['schema'] != 'h8_bound_remaining_fast_handoff_v1' or m.get('technical_plan_sealed') is not True:
        raise ValueError('HANDOFF_FINAL_SEAL_REQUIRED')
    actual = admit_heavy(m['old_parent']['directory'])
    if actual is None or digest(actual) != digest(m['accepted_heavy']):
        raise ValueError('HANDOFF_HEAVY_RECEIPT_CHANGED')
    return True
