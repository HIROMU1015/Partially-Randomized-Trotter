def read(path):
    p = Path(path)
    if p.is_symlink() or p.stat().st_size > 8*2**20:
        raise ValueError('HANDOFF_JSON_CAP_OR_LINK')
    return json.loads(p.read_text())


def private_path(path):
    p = Path(path)
    if not p.is_absolute() or not p.is_relative_to('/home/AbeHiromu') or any(x.is_symlink() for x in (p, *p.parents)):
        raise ValueError('HANDOFF_HOME_PATH')
    return p


def source_paths(root):
    return sorted(set(old_sources(root)) | {RUNNER, PREPARER, ARMER})


def inactive(identity):
    try:
        raw = Path(f"/proc/{identity['pid']}/stat").read_text()
        f = raw[raw.rfind(')')+2:].split()
    except FileNotFoundError:
        return True
    # A reused PID is not the old job. Never signal the new owner.
    return int(f[19]) != identity['start_ticks'] or f[0] in ('Z', 'X')


def require_retired_continuation(parent):
    if (parent/'remaining01').exists() or (parent/'auth-remaining01').exists():
        raise ValueError('OLD_REMAINING_ALREADY_PREPARED_OR_DISPATCHED')
    retirement = read(parent/'handoff_retired_old_continuation.json')
    term = read(parent/'PIPELINE_STOP.json')
    if (not (parent/'STOP_PIPELINE').exists() or 'USER_STOP_PIPELINE' not in term['reason']
        or retirement['pipeline_terminal'] != term or retirement['heavy_stopped'] is not False
        or retirement['remaining_old_run_started'] is not False or retirement['new_science_calls'] != 0):
        raise ValueError('OLD_CONTINUATION_NOT_RETIRED')
    if not inactive(dict(pid=retirement['retired_pipeline_pid'], start_ticks=retirement['start_ticks'])):
        raise ValueError('OLD_CONTINUATION_STILL_ACTIVE')
    return retirement


def remaining_registrations(signals):
    rows = old_registrations(OLD_SOURCE, 'REMAINING', signals)
    if [r['index'] for r in rows] != [0, 1, 2, 4, 5, 6, 7]:
        raise ValueError('HANDOFF_FIXED_SEVEN_INDICES')
    return rows


