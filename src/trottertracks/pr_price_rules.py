"""Passive, exact PR price lookup/application. No mapper, sampler, fit or Q3.

The caller supplies a generated configuration and an explicit implementation
contract. Canonical IDs and design kappa are provenance, not circuit identity.
New physical inputs are never generated by this module.
"""
from copy import deepcopy
from fractions import Fraction
from functools import lru_cache
import json
from pathlib import Path
import subprocess

AXES = ('X', 'Y')
QUANTITY = 'MEASURED_FULL_CONTROLLED_HADAMARD_WRAPPER_COMPILED_RZ_PER_SHOT'


def frac(value):
    if isinstance(value, dict):
        return Fraction(int(value['numerator']), int(value['denominator']))
    return Fraction(value)  # preserve a saved binary64 exactly, never round it


def exact(value):
    value = frac(value)
    return dict(numerator=value.numerator, denominator=value.denominator)


class GitReader:
    """Only immutable Git blobs; no import or execution of producer code."""
    def __init__(self, root):
        self.root = str(root)

    @lru_cache(maxsize=None)
    def document(self, commit, path):
        return json.loads(subprocess.check_output(
            ['git', 'show', commit + ':' + path], cwd=self.root))

    def read(self, locator):
        out = self.document(locator['commit'], locator['path'])
        for key in locator.get('selector', []):
            out = out[int(key)] if isinstance(out, list) else out[key]
        return deepcopy(out)


def _canon(value):
    """Exact semantic number comparison (including float vs rational wrappers)."""
    if isinstance(value, dict):
        if set(value) == {'numerator', 'denominator'}:
            return ('number', frac(value))
        return tuple(sorted((k, _canon(v)) for k, v in value.items()))
    if isinstance(value, list):
        return tuple(_canon(v) for v in value)
    if type(value) in (int, float):
        return ('number', frac(value))
    return value


def _same(a, b):
    return _canon(a) == _canon(b)


def _event_recipe(value):
    """Remove redundant labels/counts, retaining law SOURCE and all probabilities.

    q/R are checked in the physical row. K, weights, dictionary, phase and
    primitive SOURCE remain part of identity. No broad recursive SOURCE erasure.
    """
    if isinstance(value, dict):
        return {k: _event_recipe(v) for k, v in value.items()
                if k not in ('candidate_id', 'q_PF', 'R_outer')}
    if isinstance(value, list):
        return [_event_recipe(v) for v in value]
    return value


def family(configuration, implementation):
    s = configuration['spec']
    if s['method'] != 'PR':
        raise ValueError('Only PR-DF and PR-Pauli are supported')
    return dict(method='PR_PAULI' if s['split'].get('tail_dictionary') else 'PR_DF',
                L_D=s['L_D'], binding=s['binding'], split=s['split'],
                formula=s['formula'], K=s['finite_K'], law=s['law'],
                profile=s['profile'], implementation=implementation)


def point(row):
    """Use generated physical fields, never infer a schedule from kappa/delta."""
    q, r = row['q_PF'], row['R_outer']
    if type(q) is not int or q < 1 or type(r) is not int or r < 1:
        raise ValueError('q/R must be positive integers')
    t, step = frac(row['T']), frac(row['actual_delta_pf'])
    st = deepcopy(row['structure'])
    weights, pieces = st['signed_weights'], st['allocation']
    if t <= 0 or step <= 0 or t != q * step:
        raise ValueError('T, q and actual_delta_pf disagree')
    if len(pieces) != len(weights) or not pieces or sum(pieces) != r:
        raise ValueError('Piece allocation/R mismatch')
    if any(type(n) is not int or n < 1 for n in pieces):
        raise ValueError('Invalid piece event allocation')
    if st['event_count'] != q * r:
        raise ValueError('event_count must equal q*R')
    # The canonical candidate duplicates the mapper output. Reject stale copies.
    c = row['candidate']
    for key, value in dict(q=q, R_outer=r, T=row['T'], delta=row['actual_delta_pf'],
                           event_count=q*r).items():
        if not _same(c.get(key), value):
            raise ValueError('Canonical candidate disagrees with physical row: ' + key)
    if row.get('physical_candidate'):
        for key, value in dict(q=q, R_outer=r, T=row['T'], delta=row['actual_delta_pf']).items():
            if not _same(row['physical_candidate'].get(key), value):
                raise ValueError('Legacy physical candidate disagrees with row: ' + key)
    normalized = deepcopy(st)
    normalized['allocation'] = [exact(Fraction(n, r)) for n in pieces]
    normalized.pop('event_count')
    return dict(T=exact(t), q=q, R=r, step=exact(step), structure=st,
                piece_pattern=normalized,
                event_recipe=dict(binding=_event_recipe(row['law_binding']['definition']),
                                  round_definition=_event_recipe(row.get('round_law_definition'))),
                event_steps=[exact(step * frac(w) / n) for w, n in zip(weights, pieces)])


def physical(point_value):
    return {k: v for k, v in point_value.items() if k != 'piece_pattern'}


def _axis_source(locator, selector):
    return dict(locator, selector=locator.get('selector', []) + selector)


def _at(value, keys):
    for key in keys:
        value = value[key]
    return value


def _cell_point(configuration, q, r, t):
    anchors = [row for row in configuration['rounds'] if row['q_PF'] == q and _same(row['T'], t)]
    if len(anchors) != 1 or len(anchors[0]['structure']['allocation']) != 1:
        raise ValueError('Unsupported off-schedule cell anchor')
    anchor = deepcopy(anchors[0])
    anchor['R_outer'] = r
    anchor['structure'].update(allocation=[r], event_count=q*r)
    anchor['candidate'].update(R_outer=r, event_count=q*r)
    if anchor.get('physical_candidate'):
        anchor['physical_candidate']['R_outer'] = r
    return point(anchor)


class PriceRules:
    def __init__(self, reader, registry):
        self.reader = reader
        self.entries = deepcopy(registry['entries'])
        for e in self.entries:
            e['configuration'] = reader.read(e['configuration_source'])
            e['family'] = family(e['configuration'], e['implementation'])
            e['points'] = {r['m']: point(r) for r in e['configuration']['rounds']}
            e['saved'] = {}
            if e.get('price_source'):
                for i, row in enumerate(reader.read(e['price_source'])['rows']):
                    if 'L_D' in row and row['L_D'] != e['family']['L_D']:
                        continue
                    m, a = row['m'], row['axis']
                    if a not in AXES or m not in e['points'] or (m, a) in e['saved']:
                        raise ValueError('Invalid/duplicate saved axis')
                    p = e['points'][m]
                    if row.get('q', p['q']) != p['q'] or row.get('R', row.get('R_outer', p['R'])) != p['R']:
                        raise ValueError('Saved price q/R does not match configuration')
                    cfg_row = next(r for r in e['configuration']['rounds'] if r['m'] == m)
                    ids = {cfg_row['candidate']['id'], cfg_row.get('physical_candidate', {}).get('id')}
                    if row['physical_id'] not in ids:
                        raise ValueError('Saved price physical ID does not match configuration')
                    e['saved'][m, a] = dict(value=exact(row.get('C_ref', row.get('C_ref_exact'))),
                        source=_axis_source(e['price_source'], ['rows', i]))
                if len(e['saved']) != 26:
                    raise ValueError('Registered model must have all 26 unique axes')
            e['direct'] = []
            for group in e.get('direct_sources', []):
                for i, d in enumerate(reader.read(group['source'])):
                    if group.get('L_D') is not None and d.get('L_D') != group['L_D']:
                        continue
                    # These are saved means, not a new aggregation of observed paths.
                    a, m = d['axis'], d.get('m', group.get('m'))
                    if a not in AXES:
                        raise ValueError('Invalid direct-price axis')
                    value = _at(d, group.get('value_selector', [group.get('value_key')]))
                    if frac(value) < 0:
                        raise ValueError('Negative direct compiled count')
                    if group.get('require_valid') and d.get('valid') is not True:
                        raise ValueError('Invalid saved direct-price unit')
                    e['direct'].append(dict(m=m, axis=a, value=exact(value),
                        source=_axis_source(group['source'], [i]), role=group['role'],
                        n_paths=d.get('n_paths', group.get('n_paths')),
                        cohort=d.get('cohort', group.get('cohort')),
                        receipt_source=deepcopy(group.get('receipt_source'))))
            if e.get('model_source'):
                e['model'] = reader.read(e['model_source'])
                if e['mode'] != 'SAVED_STRUCTURAL_PLUS_RESIDUAL':
                    for (m, a), saved in e['saved'].items():
                        value, _ = self._model(e, e['points'][m], a)
                        if value != frac(saved['value']):
                            raise ValueError('Frozen coefficients do not reproduce saved unit prices')
            # A's off-schedule cells stay m=None. They are not round receipts.
            if e.get('calibration_evidence'):
                cells = reader.read(e['calibration_evidence'])
                for a in AXES:
                    rows = [d for d in cells if d['axis'] == a]
                    if len(rows) != 2 or len({d['path_id'] for d in rows}) != 2:
                        raise ValueError('Expected A two-path calibration cell')
                    if len({(d['q'], d['R'], d['physical_id']) for d in rows}) != 1:
                        raise ValueError('Mixed A calibration cell identities')
                    r, q = rows[0]['R'], rows[0]['q']
                    e['direct'].append(dict(m=None, axis=a,
                        point=_cell_point(e['configuration'], q, r, e['configuration']['rounds'][3]['T']),
                        saved_physical_id=rows[0]['physical_id'], n_paths=2,
                        value=exact(sum(Fraction(d['compiled_RZ']) for d in rows)/2),
                        source=e['calibration_evidence'], role='OFF_SCHEDULE_CALIBRATION_CELL',
                        cohort=e['name']+'_A_SAVED_CALIBRATION_CELL',
                        receipt_source=e['calibration_evidence']))
            if e.get('calibration_handoff'):
                hand = reader.read(e['calibration_handoff'])
                for i, rec in enumerate(hand['records']):
                    cell = next(c for c in hand['cells'] if c['cell_id'] == rec['cell_id'])
                    if frac(rec['features']['pf_step_count']) != cell['q'] or frac(rec['features']['event_count']) != cell['q']*cell['R']:
                        raise ValueError('Calibration record/cell features disagree')
                    e['direct'].append(dict(m=None, axis=rec['axis'],
                        point=_cell_point(e['configuration'], cell['q'], cell['R'], cell['T']),
                        saved_physical_id=cell['physical_id'], value=exact(rec['rz_count']),
                        n_paths=rec['n_paths'], cohort=cell['cohort'],
                        paired_dependence=cell['paired_dependence'],
                        role='OFF_SCHEDULE_CALIBRATION_CELL',
                        source=_axis_source(e['calibration_handoff'], ['records', i]),
                        receipt_source=_axis_source(e['calibration_handoff'], ['sidecars', i])))
            if e.get('direct_path_means'):
                paths = reader.read(e['direct_path_means'])
                for m in sorted({p['m'] for p in paths}):
                    for a in AXES:
                        chosen = [p for p in paths if p['m'] == m and p['axis'] == a]
                        if len(chosen) != 4 or {p['index'] for p in chosen} != set(range(4)):
                            raise ValueError('Expected four saved calibration paths per axis')
                        e['direct'].append(dict(m=m, axis=a, n_paths=4,
                            value=exact(sum(Fraction(p['C']) for p in chosen)/4),
                            source=e['direct_path_means'], role='CALIBRATION_P2_FRESH_ONLY',
                            cohort=chosen[0]['cohort'],
                            receipt_source=e['direct_path_means'], receipt_filter=dict(m=m, axis=a)))

    @classmethod
    def from_repo(cls, root):
        path = Path(root) / 'configs/pr_price_rules/h4_saved_rules.json'
        return cls(GitReader(root), json.loads(path.read_text()))

    def template(self, name):
        e = next(e for e in self.entries if e['name'] == name)
        return dict(configuration=deepcopy(e['configuration']),
                    implementation=deepcopy(e['implementation']), policy='MODEL')

    def _model(self, e, p, axis):
        mode, q, r = e.get('mode'), p['q'], p['R']
        if mode == 'SAVED_STRUCTURAL_PLUS_RESIDUAL':
            return None, ['E_I[S] for the new physical axis; saved structural table is point-specific']
        models = e.get('model', {}).get('models', {})
        if axis not in models and mode != 'PAULI_AUDIT':
            return None, ['full-wrapper coefficients for axis ' + axis]
        if mode == 'FULL_AFFINE_QR':
            c = models[axis]['coefficients']
            return frac(c['one']) + frac(c['q'])*q + frac(c['qR'])*q*r, []
        if mode == 'PAULI_C2':
            c = models[axis]['coefficients']
            return frac(c['one']) + frac(c['pf_step_count'])*q + frac(c['event_count'])*q*r, []
        if mode == 'FULL_AFFINE_Q_R1':
            if r != 1:
                return None, ['separate head q and tail qR slopes; R=1 calibration identifies only their sum beta']
            c = models[axis]
            return frac(c['alpha']) + frac(c['beta'])*q, []
        if mode == 'PAULI_AUDIT':
            c = e['model']['coefficients']; suffix = str(e['family']['L_D'])
            return frac(c['A'+suffix]) + frac(c['H'+suffix])*q + frac(c['E'+suffix])*q*r, []
        return None, ['candidate-specific full-wrapper price rule and axis ' + axis + ' coefficients']

    def _missing(self, fam, reasons, axis):
        pauli = fam['method'] == 'PR_PAULI'
        result = dict(reasons=reasons, missing_axes=[axis],
            calibration=(dict(rule='A + H*q + E*qR',
                coefficients=['A', 'H', 'E'],
                action='Candidate-specific compile/decomposition audit of wrapper/end runs, head boundaries and normal tail bodies; verify wrapper margins at all requested T',
                reuse='Same-candidate matching receipts only; A LD3/LD5 audited cell is a template, not transferable coefficients') if pauli else
                dict(rule='full-wrapper affine q/qR, or affine q only after all R=1 is established',
                coefficients=['offset', 'head q slope', 'tail qR slope'],
                action='Use candidate-specific same-step normal X/Y means at full-rank (1,q,qR) cells; for fixed R=1 use two distinct q, and an independent descriptive holdout',
                reuse='Matching candidate means; for LD9 m6 reuse its four-path mean and obtain a distinct q at R=1. If R varies require non-collinear q/qR cells')),
            execution_authorized=False)
        if any('E_I[S]' in r for r in reasons):
            result['calibration'] = dict(coefficients=[], missing_quantity='E_I[S] for the supplied physical axis',
                action='Reuse frozen residual coefficients only within their fixed family; supply a sourced structural expectation at the changed point. No double addition of full C.')
        elif any('separate head q' in r for r in reasons):
            result['calibration']['coefficients'] = ['separate head q slope', 'tail qR slope']
            result['calibration']['action'] = 'R=1 identifies beta=head+tail only. Add candidate-specific distinct-R means at independent feature rows to identify the two slopes; retain a descriptive holdout.'
        return result

    def quote(self, request):
        """B2 boundary: supplied configuration -> 26 exact prices or explicit needs.

        policy MODEL preserves frozen model totals and never substitutes holdout
        observations. AUTO prefers identical-physical finite-cohort direct means;
        DIRECT returns only such means. No mode promotes a price to E[C].
        """
        cfg, imp = request['configuration'], request['implementation']
        policy = request.get('policy', 'AUTO')
        if policy not in ('MODEL', 'AUTO', 'DIRECT'):
            raise ValueError('policy must be MODEL, AUTO or DIRECT')
        fam = family(cfg, imp)
        rounds = cfg['rounds']
        if len(rounds) != cfg['spec']['M']+1 or {r['m'] for r in rounds} != set(range(cfg['spec']['M']+1)):
            raise ValueError('Configuration must contain every unique round')
        matches = [e for e in self.entries if _same(e['family'], fam)]
        if len(matches) > 1:
            raise ValueError('Ambiguous registered physical family')
        e = matches[0] if matches else None
        near = [x for x in self.entries if x['family']['method'] == fam['method'] and x['family']['L_D'] == fam['L_D']]
        changed = sorted({k for x in near for k in fam if not _same(fam[k], x['family'][k])})
        out = []
        for row in sorted(rounds, key=lambda r: r['m']):
            p = point(row)
            if row['candidate']['prefix'] != fam['L_D'] or row['candidate']['formula'] != fam['formula'] or row['candidate']['K'] != fam['K']:
                raise ValueError('Candidate split/formula/K disagree with spec')
            for axis in AXES:
                item = dict(m=row['m'], axis=axis, physical_id=row['candidate']['id'],
                            q=p['q'], R=p['R'], unit_price_RZ=None, classification='NEEDS_PRICE_EVIDENCE',
                            quantity=QUANTITY, direct_alternatives=[], model_alternative=None,
                            qualified_E_C=False, CI=None)
                reasons = []
                if e:
                    same = [m for m, v in e['points'].items() if _same(physical(p), physical(v))]
                    item['direct_alternatives'] = [deepcopy(d) for d in e['direct'] if d['axis'] == axis and
                        (d['m'] in same or ('point' in d and _same(physical(d['point']), physical(p))))]
                    saved = next((e['saved'][m, axis] for m in same if (m, axis) in e['saved']), None)
                    patterns = [v for v in e['points'].values() if _same(v['piece_pattern'], p['piece_pattern']) and
                                _same(v['event_recipe'], p['event_recipe'])]
                    if saved:
                        val, src = frac(saved['value']), saved['source']
                    elif not patterns:
                        val, src = None, None
                        reasons = ['event recipe, signed pieces or relative event allocation changed; boundary/event coefficients are unsupported']
                    elif not any(_same(v['step'], p['step']) for v in patterns):
                        val, src = None, None
                        reasons = ['actual PF step/rotation angles changed; coefficients require same-step calibration or sourced audit extension']
                    elif e.get('mode') == 'PAULI_AUDIT' and not any(_same(v['T'], p['T']) for v in e['points'].values()):
                        val, src = None, None
                        reasons = ['wrapper terminal-angle/nonzero margin audit is missing at this T']
                    else:
                        val, reasons = self._model(e, p, axis)
                        src = e.get('model_source')
                    if val is not None:
                        if val <= 0:
                            reasons = ['model returns nonpositive price; no clamping']; val = None
                        else:
                            domain = e.get('calibration_domain', {})
                            extrap = [k for k in ('q', 'R') if k in domain and not domain[k][0] <= p[k] <= domain[k][1]]
                            item['model_alternative'] = dict(value=exact(val), source=src,
                                rule=e['mode'], calibration_domain=domain, extrapolation=extrap,
                                application='SAVED_MODEL_REFERENCE_REUSE' if saved else 'EXISTING_RULE_APPLICATION',
                                caveats=e.get('caveats', []) + ['finite-cohort model; no all-law expectation/CI or prediction guarantee',
                                    'q/R box membership is not independent validation'],
                                event_step_changed_from_calibration=bool(e.get('calibration_R') and p['R'] not in e['calibration_R']))
                            if e.get('calibration_evidence'):
                                item['model_alternative']['calibration_evidence'] = e['calibration_evidence']
                    item['registered_rule'] = e['name']
                else:
                    reasons = ['No matching physical family'] + ['changed: '+k for k in changed]
                direct = item['direct_alternatives']
                if request.get('direct_cohort'):
                    direct = [d for d in direct if d['cohort'] == request['direct_cohort']]
                model = item['model_alternative']
                if policy in ('DIRECT', 'AUTO') and len(direct) == 1:
                    item.update(classification='DIRECT_FINITE_COHORT', unit_price_RZ=direct[0]['value'], source=direct[0]['source'])
                elif policy != 'DIRECT' and model:
                    item.update(classification='MODEL_REFERENCE', unit_price_RZ=model['value'], source=model['source'])
                else:
                    if len(direct) > 1 and policy in ('AUTO', 'DIRECT'):
                        reasons = ['Multiple direct cohorts: choose a cohort explicitly; no pooling']
                    item['needs'] = self._missing(fam, reasons or ['No identical-physical direct price for this axis'], axis)
                out.append(item)
        total = None
        shots = request.get('shots')
        if shots is not None:
            if set(shots) != set(AXES) or any(len(shots[a]) != len(rounds) for a in AXES):
                raise ValueError('shots must contain X/Y vectors covering all rounds')
            if any(type(n) is not int or n < 0 for a in AXES for n in shots[a]):
                raise ValueError('Shot counts must be nonnegative integers')
            if all(i['unit_price_RZ'] is not None for i in out):
                total = exact(sum(shots[i['axis']][i['m']] * frac(i['unit_price_RZ']) for i in out))
            for i in out:
                i['shots'] = shots[i['axis']][i['m']]
                i['weighted_RZ'] = None if i['unit_price_RZ'] is None else exact(i['shots']*frac(i['unit_price_RZ']))
        return dict(schema='PR_PRICE_APPLICABILITY_V1', configuration_id=cfg['id'], policy=policy,
                    method=fam['method'], L_D=fam['L_D'], rows=out, total_RZ=total,
                    complete=all(i['unit_price_RZ'] is not None for i in out),
                    qualified_E_C=False, CI=None, Q3_executed=False)
